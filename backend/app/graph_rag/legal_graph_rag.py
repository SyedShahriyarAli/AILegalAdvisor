# Statute aliases that may appear in user queries, mapped to a lowercased
# substring expected to be present in the corresponding Document.title node
# in Neo4j. Order matters - longer/more-specific aliases are matched first
# so e.g. "pakistan penal code" wins over "code".
_STATUTE_ALIAS_PATTERNS: List[Tuple[str, str]] = [
    (r'prevention of electronic crimes', 'electronic crimes'),
    (r'pakistan penal code', 'penal code'),
    (r'electronic transactions', 'electronic transactions'),
    (r'pakistan telecommunication\w*', 'telecommunication'),
    (r'telecommunication\w*', 'telecommunication'),
    (r'\bpeca\b', 'electronic crimes'),
    (r'\bppc\b', 'penal code'),
    (r'penal code', 'penal code'),
    (r'\beto\b', 'electronic transactions'),
    (r'\btelecom\b', 'telecommunication'),
    (r'\bconstitution\b', 'constitution'),
]


class LegalGraphRAG:
    EMPTY_GENERATION_PLACEHOLDER = (
        "No response generated by configured model backend."
    )  # Shown when Ollama returns HTTP 200 but an empty "response" string.

    @staticmethod
    def _strip_markdown_json_fence(raw: str) -> str:
        s = (raw or "").strip()
        if not s.startswith("```"):
            return s
        lines = s.split("\n")
        if lines and lines[0].strip().startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        return "\n".join(lines).strip()

    @staticmethod
    def _normalize_env_text(value: str | None) -> str:
        if value is None:
            return ""
        return "".join(ch for ch in value if ch.isprintable() and ord(ch) < 128).strip()

    @staticmethod
    def _normalize_ollama_base_url(url: str) -> str:
        """
        OLLAMA_URL must be the origin only (e.g. https://x.ngrok-free.app).
        If someone pastes a full path used for testing (/api/tags), strip it so
        /api/generate does not become /api/tags/api/generate.
        """
        u = url.rstrip("/")
        lowered = u.lower()
        for suffix in ("/api/tags", "/api/generate"):
            if lowered.endswith(suffix):
                u = u[: -len(suffix)].rstrip("/")
                lowered = u.lower()
        return u

    def __init__(self, 
                neo4j_uri: str,
                neo4j_user: str,
                neo4j_password: str,
                ollama_url: str,
                ollama_model : str = "Llama3.1:8b"):
        self.driver = GraphDatabase.driver(neo4j_uri, auth=(neo4j_user, neo4j_password))
        self.embedding_model = SentenceTransformer('all-MiniLM-L6-v2')
        self.ollama_url = self._normalize_ollama_base_url(
            self._normalize_env_text(ollama_url)
        )
        self.model_name = self._normalize_env_text(ollama_model) or "Llama3.1:8b"
        # Remote GPU (e.g. Kaggle + ngrok): first /api/generate can exceed 120s while the model loads.
        self.ollama_request_timeout = int(os.getenv("OLLAMA_REQUEST_TIMEOUT", "300"))

        # Load query complexity classifier
        self.query_classifier = QueryComplexityClassifier()
        
        # Load re-ranker model for multi-stage retrieval
        try:
            self.reranker = CrossEncoder('cross-encoder/ms-marco-MiniLM-L-6-v2')
            self.use_reranker = True
        except Exception as e:
            print(f"Warning: Could not load re-ranker model: {e}")
            self.use_reranker = False
        
    def close(self):
        self.driver.close()

    def _ollama_http_headers(self) -> dict:
        """Free ngrok may return an HTML interstitial unless this header is set."""
        if "ngrok" in self.ollama_url.lower():
            return {"ngrok-skip-browser-warning": "true"}
        return {}

    def check_ollama_health(self) -> bool:
        """Check if Ollama service (or Ollama-compatible shim) is reachable."""
        try:
            response = requests.get(
                f"{self.ollama_url}/api/tags",
                timeout=5,
                headers=self._ollama_http_headers(),
            )
            return response.status_code == 200
        except Exception:
            return False

    def check_generation_health(self):
        ollama_ok = self.check_ollama_health()
        return {
            "backend": "ollama",
            "healthy": ollama_ok,
            "error": None if ollama_ok else "Ollama-compatible endpoint not reachable",
            "model": self.model_name,
        }

    def _generate_text(self, prompt: str, temperature: float = 0.3, num_predict: int = 800, top_p: float = 0.9) -> str:
        payload = {
            "model": self.model_name,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": temperature,
                "num_predict": num_predict,
                "top_p": top_p,
            }
        }

        response = requests.post(
            f"{self.ollama_url}/api/generate",
            json=payload,
            timeout=self.ollama_request_timeout,
            headers=self._ollama_http_headers(),
        )
        response.raise_for_status()
        data = response.json()
        if data.get("error"):
            raise RuntimeError(f"Ollama returned an error: {data['error']}")
        text = (data.get("response") or "").strip()
        return text or self.EMPTY_GENERATION_PLACEHOLDER
    
    def semantic_search(self, query: str, top_k: int = 10) -> List[Dict]:
        query_embedding = self.embedding_model.encode(query)
        
        with self.driver.session() as session:
            cypher_query = """
            CALL db.index.vector.queryNodes(
              'article_embeddings',
              $top_k,
              $query_embedding
            )
            YIELD node, score
            MATCH (d:Document)-[:CONTAINS]->(node)
            RETURN node.id as id,
                   node.article_number as article_number,
                   node.title as title,
                   node.content as content,
                   node.page_number as page_number,
                   node.chapter as chapter,
                   node.part as part,
                   d.title as document_title,
                   d.source_file as source_file,
                   score
            """
            results = session.run(
            cypher_query, 
            parameters={'query_embedding': query_embedding, 'top_k': top_k})
        
            articles = []
            for record in results:
                articles.append({
                    'id': record['id'],
                    'article_number': record['article_number'],
                    'title': record['title'],
                    'content': record['content'],
                    'page_number': record['page_number'],
                    'chapter': record['chapter'],
                    'part': record['part'],
                    'document_title': record['document_title'],
                    'source_file': record['source_file'],
                    'similarity': float(record['score']) # Score is the similarity
                })
            
            return articles
    
