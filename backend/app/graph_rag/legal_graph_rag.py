    def get_related_articles(self, article_id: str, depth: int = 2) -> List[Dict]:
        with self.driver.session() as session:
            # Enhanced to include CITES relationships
            cypher_query = """
            MATCH path = (a:Article {id: $article_id})-[:SIMILAR_TO|RELATES_TO|CITES|RELATED_THROUGH*1..""" + str(depth) + """]->(related)
            WHERE related:Article
            MATCH (d:Document)-[:CONTAINS]->(related)
            RETURN DISTINCT related.id as id,
                   related.article_number as article_number,
                   related.title as title,
                   related.content as content,
                   related.page_number as page_number,
                   related.chapter as chapter,
                   related.part as part,
                   d.title as document_title,
                   d.source_file as source_file,
                   length(path) as distance
            ORDER BY distance
            LIMIT 15
            """
            
            results = session.run(cypher_query, article_id=article_id)
            return [dict(record) for record in results]
    
